begin;

create table public.korea_products (
  id bigint generated by default as identity primary key,
  product_no text not null check (btrim(product_no) <> ''),
  product_name text not null check (btrim(product_name) <> ''),
  wholesale_price numeric(14,2),
  image_url text,
  is_active boolean not null default true,
  display_order integer not null unique,
  check (not is_active or (wholesale_price is not null and wholesale_price > 0))
);

alter table public.korea_products enable row level security;
revoke all on table public.korea_products from public, anon, authenticated;
grant select on table public.korea_products to authenticated;
create policy korea_products_active_staff_select on public.korea_products
for select to authenticated
using (
  exists (
    select 1 from public.exhibition_staff staff
    where staff.user_id = (select auth.uid()) and staff.active = true
  )
);

commit;
